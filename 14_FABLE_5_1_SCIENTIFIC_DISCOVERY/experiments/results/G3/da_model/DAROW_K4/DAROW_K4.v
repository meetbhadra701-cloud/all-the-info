module DAROW_K4(input clk, input [7:0] ph, input [6:0] c, input [63:0] x, output [1:0] y);
  wire [3:0] l0 = x[3:0];
  wire [3:0] l1 = x[7:4];
  wire [3:0] l2 = x[11:8];
  wire [3:0] l3 = x[15:12];
  wire [3:0] l4 = x[19:16];
  wire [3:0] l5 = x[23:20];
  wire [3:0] l6 = x[27:24];
  wire [3:0] l7 = x[31:28];
  wire [3:0] l8 = x[35:32];
  wire [3:0] l9 = x[39:36];
  wire [3:0] l10 = x[43:40];
  wire [3:0] l11 = x[47:44];
  wire [3:0] l12 = x[51:48];
  wire [3:0] l13 = x[55:52];
  wire [3:0] l14 = x[59:56];
  wire [3:0] l15 = x[63:60];
  wire [4:0] t0 = l0 + l1;
  wire [4:0] t1 = l2 + l3;
  wire [4:0] t2 = l4 + l5;
  wire [4:0] t3 = l6 + l7;
  wire [4:0] t4 = l8 + l9;
  wire [4:0] t5 = l10 + l11;
  wire [4:0] t6 = l12 + l13;
  wire [4:0] t7 = l14 + l15;
  wire [5:0] t8 = t0 + t1;
  wire [5:0] t9 = t2 + t3;
  wire [5:0] t10 = t4 + t5;
  wire [5:0] t11 = t6 + t7;
  wire [6:0] t12 = t8 + t9;
  wire [6:0] t13 = t10 + t11;
  wire [7:0] t14 = t12 + t13;
  reg [7:0] pc; always @(posedge clk) pc <= t14;
  wire [13:0] pce = {{6{1'b0}}, pc};
  wire cinj = (ph[1] & c[6]) | (ph[2] & c[5]) | (ph[3] & c[4]) | (ph[4] & c[3]) | (ph[5] & c[2]) | (ph[6] & c[1]) | (ph[7] & c[0]);
  reg [13:0] acc;
  wire [13:0] addend = ph[0] ? ~pce : pce;
  wire [13:0] base = ph[0] ? 14'd0 : {acc[12:0], 1'b0};
  wire cin = ph[0] | cinj;
  always @(posedge clk) acc <= base + addend + cin;
  reg [13:0] outr; always @(posedge clk) outr <= ph[0] ? acc : {2'b00, outr[13:2]};
  assign y = outr[1:0];
endmodule
