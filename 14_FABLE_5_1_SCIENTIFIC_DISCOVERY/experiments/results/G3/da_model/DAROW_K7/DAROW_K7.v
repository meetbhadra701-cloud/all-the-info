  wire [3:0] l1 = x[7:4];
  wire [3:0] l2 = x[11:8];
  wire [3:0] l3 = x[15:12];
  wire [3:0] l4 = x[19:16];
  wire [3:0] l5 = x[23:20];
  wire [3:0] l6 = x[27:24];
  wire [3:0] l7 = x[31:28];
  wire [3:0] l8 = x[35:32];
  wire [3:0] l9 = x[39:36];
  wire [4:0] t0 = l0 + l1;
  wire [4:0] t1 = l2 + l3;
  wire [4:0] t2 = l4 + l5;
  wire [4:0] t3 = l6 + l7;
  wire [4:0] t4 = l8 + l9;
  wire [5:0] t5 = t0 + t1;
  wire [5:0] t6 = t2 + t3;
  wire [6:0] t7 = t5 + t6;
  wire [7:0] t8 = t7 + t4;
  reg [7:0] pc; always @(posedge clk) pc <= t8;
  wire [13:0] pce = {{6{1'b0}}, pc};
  wire cinj = (ph[1] & c[6]) | (ph[2] & c[5]) | (ph[3] & c[4]) | (ph[4] & c[3]) | (ph[5] & c[2]) | (ph[6] & c[1]) | (ph[7] & c[0]);
