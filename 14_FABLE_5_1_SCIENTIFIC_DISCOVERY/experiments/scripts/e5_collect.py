"""Collect ORFS metrics for E5 runs and apply the (amended) pre-registered decision.

python3 e5_collect.py E5_DIR N  > ../results/E5_summary.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

CLOCK_NS = 20.0


def load(p: Path):
    try:
        return json.loads(p.read_text())
    except Exception:
        return None


def main(e5: Path, n: int):
    build = json.loads((e5 / f'build_n{n}.json').read_text())
    print(f'# E5 summary (generated by scripts/e5_collect.py; do not edit by hand) — n = m = {n}\n')
    print('SKY130 HD, ORFS (openroad/orfs image 69df744e2b5c), area-oriented module synthesis, 20 ns virtual clock (Amendment A1).')
    print('valid = our AIG simulation of the full top netlist vs numpy W@x (64 vectors) and the one-connection mutation is detected.\n')
    print('| design | valid | util % | rc | synth cell area um^2 | final cell area um^2 | core area um^2 | GRT overflow/viol | DRT DRC | routed WL um | natural delay ns |')
    print('|---|---|---|---|---|---|---|---|---|---|---|')
    res = {}
    for d in sorted(build['designs']):
        info = build['designs'][d]
        wd = e5 / f'{d}_n{n}'
        for u in (45, 60, 75):
            nick = f'{d}_n{n}_u{u}'
            base = e5 / 'orfs' / 'logs' / 'sky130hd' / nick / 'base'
            rc = (wd / f'orfs_u{u}.rc').read_text().strip() if (wd / f'orfs_u{u}.rc').exists() else 'not run'
            fp, grt, drt, fin = (load(base / f) for f in ('2_1_floorplan.json', '5_1_grt.json', '5_2_route.json', '6_report.json'))
            if rc == 'not run':
                continue
            row = {
                'rc': rc,
                'synth_area': fp and fp.get('floorplan__design__instance__area'),
                'final_area': fin and fin.get('finish__design__instance__area__stdcell'),
                'core_area': fp and fp.get('floorplan__design__core__area'),
                'grt_viol': grt and grt.get('globalroute__design__violations'),
                'drc': drt and drt.get('detailedroute__route__drc_errors'),
                'wl': drt and drt.get('detailedroute__route__wirelength'),
                'ws': fin and fin.get('finish__timing__setup__ws'),
            }
            row['delay'] = (CLOCK_NS - row['ws']) if row['ws'] is not None else None
            row['clean'] = (rc == '0' and row['drc'] == 0 and fin is not None)
            res[(d, u)] = row
            f = lambda v, p=0: '—' if v is None else (f'{v:.{p}f}' if isinstance(v, float) else str(v))
            print(f"| {d} | {info['validation'] and info['negctl_detects']} | {u} | {rc} | {f(row['synth_area'])} | {f(row['final_area'])} | "
                  f"{f(row['core_area'])} | {f(row['grt_viol'])} | {f(row['drc'])} | {f(row['wl'])} | {f(row['delay'], 2)} |")
    print('\n## Decision (Amendment A1: routed area = synthesized cell area / U_max; U_max = highest util with DRC-clean detailed route)\n')
    routed = {}
    for d in sorted(build['designs']):
        clean = [u for u in (45, 60, 75) if res.get((d, u), {}).get('clean')]
        if clean:
            u = max(clean)
            routed[d] = (res[(d, u)]['synth_area'] / (u / 100.0), u, res[(d, u)]['delay'])
            print(f'- {d}: U_max = {u}% -> routed area {routed[d][0]:.0f} um^2; natural delay {routed[d][2]:.2f} ns')
        else:
            print(f'- {d}: no DRC-clean route in tested range (or runs incomplete)')
    if 'g1' in routed:
        ubps = {d: v for d, v in routed.items() if d.startswith('ubp')}
        if ubps:
            best = min(ubps, key=lambda d: ubps[d][0])
            ratio = routed['g1'][0] / ubps[best][0]
            print(f'\n**g1 / best UBP ({best}) routed-area ratio = {ratio:.3f}**; delay ratio {best}/g1 = {ubps[best][2]/routed["g1"][2]:.2f}')
            print(f"- K5 (ratio < 1.3): {'TRIGGERED' if ratio < 1.3 else 'not triggered'}; A5 (ratio >= 1.5): {'MET' if ratio >= 1.5 else 'NOT MET'}")


if __name__ == '__main__':
    main(Path(sys.argv[1]), int(sys.argv[2]))
