"""Collect ORFS metrics for E5 / E6 runs and apply the pre-registered decision.

python3 e5_collect.py E5_DIR 32          > ../results/E5_summary.md   (bit-parallel, Amendment A1)
python3 e5_collect.py E6_DIR 64 serial   > ../results/E6_summary.md   (bit-serial, E6 pre-registration)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

MODES = {
    # nick prefix, clock ns, timing decisive?, decision labels
    'parallel': dict(prefix='', clock=20.0, timing_decisive=False, kill='K5', adv='A5', exp='E5'),
    'serial': dict(prefix='s_', clock=3.0, timing_decisive=True, kill='K6', adv='A6', exp='E6'),
}


def load(p: Path):
    try:
        return json.loads(p.read_text())
    except Exception:
        return None


def main(edir: Path, n: int, mode: str):
    M = MODES[mode]
    build = json.loads((edir / f'build_n{n}.json').read_text())
    print(f"# {M['exp']} summary (generated by scripts/e5_collect.py; do not edit by hand) — n = m = {n}\n")
    if mode == 'parallel':
        print('SKY130 HD, ORFS (openroad/orfs image 69df744e2b5c), area-oriented module synthesis, 20 ns virtual clock (Amendment A1).')
        print('valid = our AIG simulation of the full top netlist vs numpy W@x (64 vectors) and the one-connection mutation is detected.\n')
    else:
        print('SKY130 HD, ORFS (openroad/orfs image 69df744e2b5c), area-oriented module synthesis + dfflibmap, real 3.0 ns clock with CTS (E6 pre-registration).')
        print('valid = our cycle-accurate sequential AIG simulation of the full top netlist vs numpy W@x (12 back-to-back words) and the one-connection mutation is detected.\n')
    print('| design | valid | util % | rc | synth cell area um^2 | final cell area um^2 | core area um^2 | GRT viol | DRT DRC | routed WL um | setup WS ns | hold WS ns | delay/period ns |')
    print('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    res = {}
    f = lambda v, p=0: '—' if v is None else (f'{v:.{p}f}' if isinstance(v, float) else str(v))
    for d in sorted(build['designs']):
        info = build['designs'][d]
        wd = edir / f'{d}_n{n}'
        for u in (45, 60, 75):
            nick = f"{M['prefix']}{d}_n{n}_u{u}"
            base = edir / 'orfs' / 'logs' / 'sky130hd' / nick / 'base'
            rcf = wd / f'orfs_u{u}.rc'
            if not rcf.exists():
                continue
            rc = rcf.read_text().strip()
            fp, grt, drt, fin = (load(base / x) for x in ('2_1_floorplan.json', '5_1_grt.json', '5_2_route.json', '6_report.json'))
            row = {
                'rc': rc,
                'synth_area': fp and fp.get('floorplan__design__instance__area'),
                'final_area': fin and fin.get('finish__design__instance__area__stdcell'),
                'core_area': fp and fp.get('floorplan__design__core__area'),
                'grt_viol': grt and grt.get('globalroute__design__violations'),
                'drc': drt and drt.get('detailedroute__route__drc_errors'),
                'wl': drt and drt.get('detailedroute__route__wirelength'),
                'ws': fin and fin.get('finish__timing__setup__ws'),
                'hws': fin and fin.get('finish__timing__hold__ws'),
            }
            row['delay'] = (M['clock'] - row['ws']) if row['ws'] is not None else None
            row['clean'] = (rc == '0' and row['drc'] == 0 and fin is not None)
            if M['timing_decisive']:
                row['clean'] = row['clean'] and row['ws'] is not None and row['ws'] >= 0 and (row['hws'] is None or row['hws'] >= 0)
            res[(d, u)] = row
            print(f"| {d} | {info['validation'] and info['negctl_detects']} | {u} | {rc} | {f(row['synth_area'])} | {f(row['final_area'])} | "
                  f"{f(row['core_area'])} | {f(row['grt_viol'])} | {f(row['drc'])} | {f(row['wl'])} | {f(row['ws'], 3)} | {f(row['hws'], 3)} | {f(row['delay'], 2)} |")
    if mode == 'serial':
        print('\nLatency (cycles from word start to first output bit) and throughput (cycles per word), from build_n64.json:\n')
        for d in sorted(build['designs']):
            info = build['designs'][d]
            print(f"- {d}: latency {info['latency_cycles']} cycles, {info['cycles_per_word']} cycles/word")
    crit = 'DRC-clean detailed route, setup and hold met at 3.0 ns' if M['timing_decisive'] else 'DRC-clean detailed route'
    print(f'\n## Decision (routed area = synthesized cell area / U_max; U_max = highest util with {crit})\n')
    routed = {}
    for d in sorted(build['designs']):
        clean = [u for u in (45, 60, 75) if res.get((d, u), {}).get('clean')]
        if clean:
            u = max(clean)
            r = res[(d, u)]
            routed[d] = dict(area=r['synth_area'] / (u / 100.0), final=r['final_area'] / (u / 100.0), u=u, delay=r['delay'], wl=r['wl'])
            print(f"- {d}: U_max = {u}% -> routed area {routed[d]['area']:.0f} um^2 (final-cell-area basis {routed[d]['final']:.0f}); "
                  f"{'min period' if mode == 'serial' else 'natural delay'} {r['delay']:.2f} ns; routed WL {r['wl']}")
        else:
            print(f'- {d}: no qualifying route in tested range (or runs incomplete)')
    if 'g1' in routed:
        ubps = {d: v for d, v in routed.items() if d.startswith('ubp')}
        if ubps:
            best = min(ubps, key=lambda d: ubps[d]['area'])
            ratio = routed['g1']['area'] / ubps[best]['area']
            ratio_f = routed['g1']['final'] / ubps[best]['final']
            print(f"\n**g1 / best UBP ({best}) routed-area ratio = {ratio:.3f}** (final-cell-area basis {ratio_f:.3f}); "
                  f"delay ratio {best}/g1 = {ubps[best]['delay'] / routed['g1']['delay']:.2f}; WL ratio g1/{best} = {routed['g1']['wl'] / ubps[best]['wl']:.2f}")
            for d, v in sorted(ubps.items()):
                print(f"- g1 / {d} = {routed['g1']['area'] / v['area']:.3f}")
            print(f"- {M['kill']} (ratio < 1.3): {'TRIGGERED' if ratio < 1.3 else 'not triggered'}; {M['adv']} (ratio >= 1.5): {'MET' if ratio >= 1.5 else 'NOT MET'}")
        elif all(res.get((d, u)) for d in build['designs'] for u in (60, 75)):
            print(f"\n**No UBP variant qualifies where g1 does -> {M['kill']} TRIGGERED**")


if __name__ == '__main__':
    main(Path(sys.argv[1]), int(sys.argv[2]), sys.argv[3] if len(sys.argv) > 3 else 'parallel')
