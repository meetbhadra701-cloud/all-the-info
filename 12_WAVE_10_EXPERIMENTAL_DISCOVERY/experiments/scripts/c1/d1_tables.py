#!/usr/bin/env python3
"""Builds the D1 markdown tables from the analysis outputs (no hand-typed numbers).
Inputs: experiments/results/c1_d1_summary.json, c1_d1_isodelay.csv, c1_d1/*.jsonl,
        experiments/inputs/c1/paper_table2_transcribed.csv
Output: experiments/results/c1_d1_tables.md
"""
import collections
import csv
import json
import math
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
RES = os.path.join(ROOT, "experiments", "results")
EPFL = "adder bar div hyp log2 max multiplier sin sqrt square arbiter cavlc ctrl dec i2c int2float mem_ctrl priority router voter".split()
V = ["gpt5_it29", "deepseek_it24", "qwen_it20"]


def f4(x):
    return "n/a" if x in (None, "") else "%.4f" % float(x)


def gmean(xs):
    xs = [float(x) for x in xs if x not in (None, "")]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else None


def main():
    S = json.load(open(os.path.join(RES, "c1_d1_summary.json")))
    rows = list(csv.DictReader(open(os.path.join(RES, "c1_d1_isodelay.csv"))))
    out = ["# D1 tables (generated by d1_tables.py)\n"]
    out.append("## Suite summary: geomean of A_evolved / A_baseline at the evolved mapper's own delay D_e (wins = circuits with ratio < 1)\n")
    out.append("| suite | variant | vs initial@D_e | vs emap@D_e | vs ABC &nf -p@≤D_e | **vs best baseline** (pre-registered) | vs front (post hoc) |")
    out.append("|---|---|---|---|---|---|---|")
    for s, sd in S["suites"].items():
        for v in V:
            d = sd["variants"][v]
            cell = lambda k: "%s (%d/%d)" % (f4(d["gmean_" + k]), d["wins_" + k], d["n_" + k])
            out.append("| %s | %s | %s | %s | %s | **%s** | %s |" % (s, v, cell("r_init"), cell("r_emap"), cell("r_nfp"), cell("r_best"), cell("r_front")))
    out.append("")
    out.append("## Decomposition of the headline area ratio (geomeans; exact: total = relaxation × operator)\n")
    out.append("| suite | variant | vs mockturtle map: total | = relaxation | × operator | vs ABC &nf: total | = relaxation | × operator |")
    out.append("|---|---|---|---|---|---|---|---|")
    for s, sd in S["suites"].items():
        for v in V:
            d = sd["variants"][v]
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (s, v, f4(d["gmean_dec_mt_total"]), f4(d["gmean_dec_mt_relax"]), f4(d["gmean_dec_mt_oper"]),
                                                                 f4(d["gmean_dec_abc_total"]), f4(d["gmean_dec_abc_relax"]), f4(d["gmean_dec_abc_oper"])))
    out.append("")
    out.append("## Which baseline was best at D_e (count of circuits)\n")
    out.append("| suite | variant | emap | ABC &nf -p | initial map | none met D_e |")
    out.append("|---|---|---|---|---|---|")
    suites = {"EPFL-20": EPFL, "IWLS05-22": None, "ISCAS85-11": None}
    for s in S["suites"]:
        for v in V:
            c = collections.Counter()
            for r in rows:
                if r["variant"] != v or r["status"] != "ok":
                    continue
                inset = (r["bench"] in EPFL) if s == "EPFL-20" else ((r["bench"].startswith("c") and r["bench"][1:].isdigit()) if s == "ISCAS85-11" else (r["bench"] not in EPFL and not (r["bench"].startswith("c") and r["bench"][1:].isdigit())))
                if inset:
                    c[r["best_name"] or "none"] += 1
            out.append("| %s | %s | %d | %d | %d | %d |" % (s, v, c["emap"], c["nfp"], c["init"], c["none"]))
    out.append("")
    out.append("## Per-circuit, EPFL-20, GPT-5 it29 (the paper's headline mapper)\n")
    out.append("| circuit | A_e | D_e | /initial@D_e | /emap@D_e | /ABC@≤D_e | /best | best |")
    out.append("|---|---|---|---|---|---|---|---|")
    for b in EPFL:
        r = next((r for r in rows if r["bench"] == b and r["variant"] == "gpt5_it29"), None)
        if r:
            out.append("| %s | %.2f | %.2f | %s | %s | %s | %s | %s |" % (b, float(r["A_e"]), float(r["D_e"]), f4(r["r_init"]), f4(r["r_emap"]), f4(r["r_nfp"]), f4(r["r_best"]), r["best_name"] or "-"))
    out.append("")
    # the paper's ABC column against our ABC &nf default on the identical compress2 AIG
    paper = {r["benchmark"]: r for r in csv.DictReader(open(os.path.join(ROOT, "experiments", "inputs", "c1", "paper_table2_transcribed.csv"), encoding="utf-8"))}
    out.append("## The paper's ABC column vs our yosys-abc `&nf` (default) on the identical compress2 AIG\n")
    out.append("| circuit | paper ABC area | our &nf area | our/paper | paper ABC delay | our &nf delay |")
    out.append("|---|---|---|---|---|---|")
    ratios, g_paper, g_ours = [], [], []
    for b in EPFL:
        recs = {json.loads(l)["tag"]: json.loads(l) for l in open(os.path.join(RES, "c1_d1", b + ".jsonl"))}
        nf, e = recs["B:nf"], recs["E:gpt5_it29"]
        pa, pdl = float(paper[b]["ABC_area"]), float(paper[b]["ABC_delay"])
        ratios.append(nf["eval_area"] / pa)
        g_paper.append(e["eval_area"] / pa); g_ours.append(e["eval_area"] / nf["eval_area"])
        out.append("| %s | %.2f | %.2f | %.4f | %.2f | %.2f |" % (b, pa, nf["eval_area"], nf["eval_area"] / pa, pdl, nf["eval_delay"]))
    am = lambda xs: sum(xs) / len(xs)
    out.append("")
    out.append("Arithmetic mean of our &nf / paper ABC area: **%.4f**. GPT-5 it29 area ratio (the paper's metric, arithmetic mean): **%.4f** against the paper's ABC column (the paper's \"10.04%%\"), **%.4f** against our ABC &nf default.\n" % (am(ratios), am(g_paper), am(g_ours)))
    open(os.path.join(RES, "c1_d1_tables.md"), "w", encoding="utf-8").write("\n".join(out))
    print("\n".join(out[:40]))
    print(out[-2])


if __name__ == "__main__":
    main()
