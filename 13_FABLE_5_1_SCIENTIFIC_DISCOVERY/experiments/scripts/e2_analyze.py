"""Summarize E2 against the pre-registered K2a/K2b/ADV conditions.

python3 e2_analyze.py ../results/E2_p33/E2_results.json ../results/E2_p50/E2_results.json > ../results/E2_summary.md
"""
from __future__ import annotations

import json
import sys


def main(paths):
    res = []
    for path in paths:
        res.extend(json.load(open(path)))
    print('# E2 summary (generated by scripts/e2_analyze.py; do not edit by hand)\n')
    print('SKY130 HD tt_025C_1v80; Yosys 0.69 elaboration, native ABC `strash; dch; map [-D D*]`.')
    print('"delay" is the mapper (load-independent) delay used by `map -D`; "stime" is ABC load-aware STA.')
    print('Valid = independent AIG simulation vs numpy passed AND ABC cec "Networks are equivalent".\n')
    for r in res:
        d = r['designs']
        dstar = next(iter(d.values()))['D_star']
        print(f"## n=m={r['n']}, p0={r['p0']}, seed {r['seed']}; D* = {dstar:.1f} ps (slowest delay-oriented mapping)\n")
        print('| design | U | B | AIG ANDs | delay-map area | delay-map delay ps | ISO area @D* | ISO delay ps | ISO stime delay ps | valid |')
        print('|---|---|---|---|---|---|---|---|---|---|')
        for name, x in d.items():
            md, mi = x['map_delay'], x['map_iso']
            valid = x['aig_check'] and md['cec'] and mi['cec']
            print(f"| {name} | {x.get('U', '—')} | {x.get('B', '—')} | {x['aig_ands']} | {md['area']:.0f} | {md['delay_ps']:.0f} | "
                  f"{mi['area']:.0f} | {mi['delay_ps']:.0f} | {mi['delay_stime_ps']:.0f} | {'yes' if valid else 'NO'} |")
        iso = {k: v['map_iso']['area'] for k, v in d.items()}
        ubp = min(v for k, v in iso.items() if k.startswith('ubp'))
        ubp_name = min((v, k) for k, v in iso.items() if k.startswith('ubp'))[1]
        print(f"\n- g1 / best UBP ({ubp_name}) at iso-delay: **{iso['g1']/ubp:.3f}**")
        print(f"- beh / best UBP at iso-delay: **{iso['beh']/ubp:.3f}**")
        print(f"- best UBP / da4ml at iso-delay (price of universality, cell area): **{ubp/iso['da4ml']:.3f}**")
        print(f"- cbp4 / da4ml at iso-delay: {iso['cbp4']/iso['da4ml']:.3f}\n")
        r['_g1_ubp'] = iso['g1'] / ubp
        r['_beh_ubp'] = iso['beh'] / ubp
    print('## Pre-registered conditions\n')
    g = [r['_g1_ubp'] for r in res]
    b = [r['_beh_ubp'] for r in res]
    print(f"- K2a: g1/best-UBP < 1.3 for both p0? values={['%.3f' % x for x in g]} -> {'KILL' if all(x < 1.3 for x in g) else 'not killed'}")
    print(f"- K2b: beh <= 1.2 x best-UBP? values={['%.3f' % x for x in b]} -> {'KILL' if any(x <= 1.2 for x in b) else 'not killed'}")
    adv = all(x >= 1.5 for x in g) and all(x >= 1.3 for x in b)
    print(f"- ADV (g1/UBP >= 1.5 and beh/UBP >= 1.3 for all): {'MET' if adv else 'NOT MET'}")


if __name__ == '__main__':
    main(sys.argv[1:])
