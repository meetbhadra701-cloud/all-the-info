"""Summarize E1 (../results/E1_ternary.jsonl) against the pre-registered K1/K2/A1 conditions.

python3 e1_analyze.py ../results/E1_ternary.jsonl > ../results/E1_summary.md
"""
from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict


def main(path):
    recs = [json.loads(line) for line in open(path)]
    by = defaultdict(list)
    for r in recs:
        by[(r['n'], r['p0'])].append(r)
    print('# E1 summary (generated by scripts/e1_analyze.py; do not edit by hand)\n')
    print('Unit cost U = adders; B = bit-weighted adders (result widths). Medians over seeds.')
    print('"check" = all constructions of that cell passed the independent numeric check (None = cost-only mode).\n')
    print('| n=m | p0 | seeds | g1 U | best UBP (g*) U | g1/UBP* (U) | g1/UBP* (B) | best CBP (g) U | da4ml U | UBP*/da4ml (U) | UBP*/da4ml (B) | CBP*/da4ml (U) | da4ml wall s | checks |')
    print('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    verdict_rows = []
    for (n, p0), rs in sorted(by.items()):
        def best(prefix, key='U'):
            vals = []
            for r in rs:
                ks = [k for k in r if k.startswith(prefix)]
                k = min(ks, key=lambda k: r[k]['U'])
                vals.append((r[k]['U'], r[k]['B'], k))
            return vals
        g1U = [r['g1']['U'] for r in rs]; g1B = [r['g1']['B'] for r in rs]
        ub = best('UBP'); cb = best('CBP')
        da = [r['da4ml'] for r in rs if 'U' in r.get('da4ml', {})]
        da_to = [r['da4ml'] for r in rs if r.get('da4ml', {}).get('timeout')]
        checks = []
        for r in rs:
            for k, v in r.items():
                if isinstance(v, dict) and 'check' in v:
                    checks.append(v['check'])
        ok = 'all pass' if all(c in (True, None) for c in checks) and any(c for c in checks) else ('cost-only' if all(c is None for c in checks) else 'FAIL')
        r1U = st.median([a / b[0] for a, b in zip(g1U, ub)])
        r1B = st.median([a / b[1] for a, b in zip(g1B, ub)])
        gstar = st.mode([b[2] for b in ub])
        cstar = st.mode([b[2] for b in cb])
        if da:
            daU = st.median([d['U'] for d in da]); daB = st.median([d['B'] for d in da])
            r2U = st.median([b[0] / d['U'] for b, d in zip(ub, da)])
            r2B = st.median([b[1] / d['B'] for b, d in zip(ub, da)])
            r3U = st.median([c[0] / d['U'] for c, d in zip(cb, da)])
            dw = st.median([d['wall'] for d in da])
            da_s = f'{daU:.0f}'
            r2s, r2Bs, r3s, dws = f'{r2U:.3f}', f'{r2B:.3f}', f'{r3U:.3f}', f'{dw:.1f}'
        else:
            da_s = 'timeout >600 s' if da_to else 'not run'
            r2s = r2Bs = r3s = dws = '—'
            r2U = None
        print(f'| {n} | {p0} | {len(rs)} | {st.median(g1U):.0f} | {st.median([b[0] for b in ub]):.0f} ({gstar}) | {r1U:.3f} | {r1B:.3f} | '
              f'{st.median([c[0] for c in cb]):.0f} ({cstar}) | {da_s} | {r2s} | {r2Bs} | {r3s} | {dws} | {ok} |')
        verdict_rows.append((n, p0, r1U, r1B, r2U))
    print('\n## Pre-registered conditions\n')
    k1 = [(n, p0, r1U, r1B) for n, p0, r1U, r1B, _ in verdict_rows if n >= 1024]
    if k1:
        med = st.median([min(a, b) for _, _, a, b in k1])
        print(f'- K1 (median g1/UBP* at n>=1024, conservative min of U and B ratios) = {med:.3f} '
              f'-> {"KILL" if med < 1.5 else "not killed"}; A1 part (>=2) -> {"met" if med >= 2 else "not met"}')
    k2 = [r2 for n, p0, _, _, r2 in verdict_rows if r2 is not None]
    if k2:
        med2 = st.median(k2)
        print(f'- K2 (median UBP*/da4ml where da4ml finished) = {med2:.3f} -> {"KILL" if med2 > 1.5 else "not killed"}; '
              f'A1 part (<=1.25) -> {"met" if med2 <= 1.25 else "not met"}')


if __name__ == '__main__':
    main(sys.argv[1])
